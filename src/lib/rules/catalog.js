const PRECEDENCE_ORDER = Object.freeze([
  { level: 1, label: 'root', description: 'Constitutional and non-bypassable legislative boundaries.' },
  { level: 2, label: 'hard', description: 'Deterministic CLI/runtime checks with direct input/output contracts.' },
  { level: 3, label: 'master', description: 'Highest-precedence agent orchestration rules.' },
  { level: 4, label: 'soft', description: 'Contextual agent behavior and communication rules.' },
]);

function normalizeCatalogEntry(entry) {
  return {
    id: entry.id,
    title: entry.title || entry.id,
    description: entry.description || null,
    severity: entry.severity || 'info',
    kind: entry.kind || RULE_KIND.SOFT,
    layer: entry.layer || RULE_LAYER.AGENT,
    scope: Array.isArray(entry.scope) ? entry.scope : [],
    priority: entry.priority || RULE_PRIORITY.P2,
    source_doc: entry.source_doc || null,
    source_anchor: entry.source_anchor || null,
    dependsOn: Array.isArray(entry.dependsOn) ? entry.dependsOn : [],
    overrideMode: entry.overrideMode || 'none',
    tools: Array.isArray(entry.tools) ? entry.tools : [],
    precedence: entry.precedence || inferPrecedence(entry.kind, entry.layer),
  };
}

function inferPrecedence(kind, layer) {
  if (layer === RULE_LAYER.ROOT) return 1;
  if (kind === RULE_KIND.HARD) return 2;
  if (kind === RULE_KIND.MASTER) return 3;
  return 4;
}

function listSoftRules() {
  return SOFT_RULES.map(normalizeCatalogEntry);
}

function listHardRules() {
  return loadRules().map((rule) => normalizeCatalogEntry({
    id: rule.id,
    title: rule.id,
    description: rule.description,
    severity: rule.severity,
    source_doc: rule.source_doc,
    ...HARD_RULE_METADATA[rule.id],
  }));
}

function listRuleCatalog() {
  return [...listHardRules(), ...listSoftRules()].sort((left, right) => left.id.localeCompare(right.id));
}

function listRulePacks() {
  const catalog = listRuleCatalog();
  const byId = new Map(catalog.map((rule) => [rule.id, rule]));
  return RULE_PACKS.map((pack) => {
    const rules = pack.ruleIds.map((ruleId) => byId.get(ruleId)).filter(Boolean);
    return {
      id: pack.id,
      title: pack.title,
      context: pack.context,
      description: pack.description,
      ruleIds: pack.ruleIds,
      stats: {
        count: rules.length,
        hardCount: rules.filter((rule) => rule.kind === RULE_KIND.HARD).length,
        masterCount: rules.filter((rule) => rule.kind === RULE_KIND.MASTER).length,
        softCount: rules.filter((rule) => rule.kind === RULE_KIND.SOFT).length,
        toolCoverage: rules.filter((rule) => Array.isArray(rule.tools) && rule.tools.length > 0).length,
      },
    };
  });
}

function listPrecedenceOrder() {
  return [...PRECEDENCE_ORDER];
}

